-- ÓRBITA · esquema inicial (PostgreSQL). Lo aplica Flyway al arrancar orbita-api (Esquema.preparar).
-- Las migraciones nunca se editan una vez publicadas: un cambio de esquema es un fichero nuevo, V2__..., V3__...

CREATE TABLE EMPLEADO (
    USUARIO VARCHAR(64) PRIMARY KEY,
    NOMBRE VARCHAR(120) NOT NULL,
    PUESTO VARCHAR(120),
    DEPARTAMENTO VARCHAR(80),
    RESPONSABLE VARCHAR(64),
    ROL VARCHAR(16) NOT NULL,
    DIAS_VACACIONES INT NOT NULL,
    DIAS_PROPIOS INT NOT NULL,
    PIN VARCHAR(8),
    TARJETA VARCHAR(40)
);

CREATE TABLE FESTIVO (
    FECHA DATE PRIMARY KEY,
    NOMBRE VARCHAR(80) NOT NULL
);

-- Registro de jornada: solo se añaden marcas (las correcciones aprobadas entran con ORIGEN = CORRECCION)
CREATE TABLE FICHAJE (
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USUARIO VARCHAR(64) NOT NULL,
    TIPO VARCHAR(10) NOT NULL,
    MOMENTO TIMESTAMP NOT NULL,
    MODALIDAD VARCHAR(12) NOT NULL,
    ORIGEN VARCHAR(12) NOT NULL,
    CREADO TIMESTAMP NOT NULL,
    INCIDENCIA VARCHAR(12),            -- motivo de la pausa (desayuno, comida, médico...)
    LAT DOUBLE PRECISION,              -- ubicación del dispositivo al fichar
    LON DOUBLE PRECISION,
    PRECISION_M INT
);
CREATE INDEX FICHAJE_USUARIO ON FICHAJE (USUARIO, MOMENTO);

CREATE TABLE CORRECCION (
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USUARIO VARCHAR(64) NOT NULL,
    FECHA DATE NOT NULL,
    TIPO VARCHAR(10) NOT NULL,
    HORA TIME NOT NULL,
    MOTIVO VARCHAR(500),
    ESTADO VARCHAR(12) NOT NULL,
    APROBADOR VARCHAR(64),
    COMENTARIO VARCHAR(500),
    CREADO TIMESTAMP NOT NULL,
    RESUELTO TIMESTAMP
);

CREATE TABLE AUSENCIA (
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USUARIO VARCHAR(64) NOT NULL,
    TIPO VARCHAR(20) NOT NULL,
    DESDE DATE NOT NULL,
    HASTA DATE NOT NULL,
    DIAS INT NOT NULL,
    COMENTARIO VARCHAR(500),
    ESTADO VARCHAR(12) NOT NULL,
    APROBADOR VARCHAR(64),
    COMENTARIO_RESP VARCHAR(500),
    CREADO TIMESTAMP NOT NULL,
    RESUELTO TIMESTAMP
);
CREATE INDEX AUSENCIA_USUARIO ON AUSENCIA (USUARIO, DESDE);

-- Gastos y viajes: importes en céntimos (IVA incluido en IMPORTE)
CREATE TABLE VIAJE (
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USUARIO VARCHAR(64) NOT NULL,
    DESTINO VARCHAR(120) NOT NULL,
    MOTIVO VARCHAR(500),
    DESDE DATE NOT NULL,
    HASTA DATE NOT NULL,
    ESTIMADO INT NOT NULL,
    ESTADO VARCHAR(12) NOT NULL,
    APROBADOR VARCHAR(64),
    COMENTARIO_RESP VARCHAR(500),
    CREADO TIMESTAMP NOT NULL,
    RESUELTO TIMESTAMP
);

CREATE TABLE NOTA_GASTO (
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USUARIO VARCHAR(64) NOT NULL,
    TITULO VARCHAR(160) NOT NULL,
    VIAJE INT,
    ESTADO VARCHAR(12) NOT NULL,
    APROBADOR VARCHAR(64),
    COMENTARIO_RESP VARCHAR(500),
    PAGADOR VARCHAR(64),
    CREADO TIMESTAMP NOT NULL,
    ENVIADO TIMESTAMP,
    RESUELTO TIMESTAMP,
    PAGADO TIMESTAMP
);

CREATE TABLE LINEA_GASTO (
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOTA INT NOT NULL,
    FECHA DATE NOT NULL,
    CATEGORIA VARCHAR(16) NOT NULL,
    DESCRIPCION VARCHAR(200),
    IMPORTE INT NOT NULL,
    IVA INT NOT NULL,
    KM INT,
    JUSTIFICACION VARCHAR(500),
    TICKET_NOMBRE VARCHAR(120),
    TICKET_TIPO VARCHAR(60),
    TICKET BYTEA
);
CREATE INDEX LINEA_NOTA ON LINEA_GASTO (NOTA);

-- Conversación de cada solicitud (CLASE: AUSENCIA, CORRECCION, NOTA, VIAJE) y avisos para cada persona
CREATE TABLE COMENTARIO (
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CLASE VARCHAR(12) NOT NULL,
    OBJETO INT NOT NULL,
    USUARIO VARCHAR(64) NOT NULL,
    TEXTO VARCHAR(1000) NOT NULL,
    CREADO TIMESTAMP NOT NULL
);
CREATE INDEX COMENTARIO_OBJETO ON COMENTARIO (CLASE, OBJETO);

CREATE TABLE AVISO (
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USUARIO VARCHAR(64) NOT NULL,
    APP VARCHAR(16) NOT NULL,
    CLASE VARCHAR(12),
    OBJETO INT,
    TEXTO VARCHAR(300) NOT NULL,
    LEIDO SMALLINT NOT NULL,
    CREADO TIMESTAMP NOT NULL
);
CREATE INDEX AVISO_USUARIO ON AVISO (USUARIO, CREADO);
