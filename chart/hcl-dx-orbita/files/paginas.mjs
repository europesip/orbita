// ÓRBITA · XMLAccess request with one page per application (see after-push.sh). Prints nothing if pages are disabled.
//   node paginas.mjs <paginas.json> <APP_IDS_FILE: "name<TAB>content ID" lines> [file with the existing pages]
// A page that already exists keeps its layout and its Web Content Viewer instance: only its title, parameters and
// access are updated. So the settings of each application instance (edit mode, DX preferences) survive upgrades.
import {readFileSync} from 'node:fs';

const [cfgFile, idsFile, existentesFile] = process.argv.slice(2);
const cfg = JSON.parse(readFileSync(cfgFile, 'utf8'));
if (!cfg.create) process.exit(0);
let existentes = new Set();
try { existentes = new Set(readFileSync(existentesFile, 'utf8').split('\n').map((l) => l.trim()).filter(Boolean)); } catch (e) { /* none */ }
const ids = Object.fromEntries(readFileSync(idsFile, 'utf8').split('\n').filter(Boolean).map((l) => l.split('\t')));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const cdata = (s) => `<![CDATA[${String(s).replace(/]]>/g, ']]]]><![CDATA[>')}]]>`;
const pref = (k, v) => `<preferences name="${k}" update="set"><value>${cdata(v)}</value></preferences>`;
const param = (k, v) => `<parameter name="${k}" type="string" update="set">${cdata(v)}</parameter>`;

const paginas = cfg.titles.map((t, n) => {
  const id = ids[`orbita-${t.friendly}`];
  if (!id) throw new Error(`no WCM content ID for orbita-${t.friendly} (is it in scriptapps.apps?)`);
  return `
    <content-node action="update" active="true" allportletsallowed="true" content-parentref="padre" create-type="explicit"
        domain="rel" objectid="p${n}" ordinal="${1000 + n * 100}" type="staticpage" uniquename="orbita.${esc(t.friendly)}">
      <supported-markup markup="html" update="set"/>
      <localedata locale="es"><title>${esc(t.es)}</title></localedata>
      <localedata locale="en"><title>${esc(t.en)}</title></localedata>
      ${param('com.ibm.portal.bookmarkable', 'Yes')}
      ${param('com.ibm.portal.friendly.name', t.friendly)}
      ${param('com.ibm.portal.layout.template.file.name.html', 'layout.html')}
      ${param('com.ibm.portal.layout.template.markup', 'html')}
      ${param('com.ibm.portal.layout.template.ref', cfg.layoutTemplate)}
      ${param('com.ibm.portal.static.page.file.name.html', 'layout.html')}
      <access-control externalized="false" owner="undefined" private="false"><role actionset="User" update="set">
        <mapping subjectid="anonymous portal user" subjecttype="user" update="remove"/>
        <mapping subjectid="all authenticated portal users" subjecttype="user_group" update="set"/>
      </role></access-control>${existentes.has(t.friendly) ? '' : `
      <component action="update" active="true" domain="rel" ordinal="100" orientation="V" type="container">
        <component action="update" active="true" domain="rel" ordinal="100" orientation="H" type="container">
          ${param('com.ibm.portal.layoutnode.localname', 'ibmHiddenWidgets')}
          ${param('css-classes', 'ibmDndRow hiddenWidgetsContainer wpthemeCol12of12 wpthemeFull')}
        </component>
        <component action="update" active="true" domain="rel" ordinal="200" orientation="H" type="container">
          ${param('com.ibm.portal.layoutnode.localname', 'ibmMainContainer')}
          ${param('css-classes', 'wpthemeLeft wpthemeCol ibmDndColumn wpthemeCol12of12 wpthemeFull wpthemePrimary')}
          <component action="update" active="true" domain="rel" ordinal="100" type="control" skinref="piel">
            <portletinstance action="update" domain="rel" portletref="visor">
              ${pref('WCM_CONTENT_TYPE', 'CONTENT')}
              ${pref('WCM_CONTENT_CONTEXT_TYPE', 'content')}
              ${pref('WCM_CONTENT_CONTEXT_IDR', id)}
              ${pref('WCM_CONTENT_CONTEXT_IS_REL_PATH', 'false')}
              ${pref('WCM_BROADCASTS_TO', 'WCM_LINKING_NONE')}
              ${pref('WCM_LISTENS_TO', 'WCM_LINKING_NONE')}
              ${pref('WCM_PAGE_TITLE_TYPE', 'WCM_PAGE_TITLE_TYPE_DEFAULT')}
              ${pref('WCM_PORTLET_TITLE_TYPE', 'WCM_PORTLET_TITLE_TYPE_DYN')}
            </portletinstance>
          </component>
        </component>
      </component>`}
    </content-node>`;
});

process.stdout.write(`<?xml version="1.0" encoding="UTF-8"?>
<!-- ÓRBITA · pages of the Script Applications (generated by the chart hcl-dx-orbita) -->
<request xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="PortalConfig_8.5.0.xsd"
    type="update" create-oids="true">
  <portal action="locate">
    <skin action="locate" objectid="piel" uniquename="${esc(cfg.skin)}"/>
    <web-app action="locate" uid="ilwwcm-localrenderingportlet-jsr.war.webmod">
      <portlet-app action="locate" uid="ilwwcm-localrenderingportlet-jsr.war">
        <portlet action="locate" objectid="visor" name="Web Content Viewer (JSR 286)"/>
      </portlet-app>
    </web-app>
    <content-node action="locate" objectid="padre" uniquename="${esc(cfg.parent)}"/>${paginas.join('')}
  </portal>
</request>
`);
